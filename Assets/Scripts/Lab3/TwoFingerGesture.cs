/// <summary>
/// Спільний стан жесту двома пальцями.
/// Потрібен, щоб жести не конфліктували: коли почався pinch - обертання
/// не працює, коли почалось обертання - масштабування не працює.
/// Скидається, коли на екрані вже не два пальці.
/// </summary>
public static class TwoFingerGesture
{
    public enum Mode
    {
        None,   // жест ще не визначено
        Pinch,  // пальці зводяться / розводяться -> масштаб
        Rotate  // пальці рухаються в одному напрямку -> обертання
    }

    public static Mode Current = Mode.None;
}
